# int – цілі числа
age = 10

# float – дробові числа
a = 4.19

# str – текст
name = "Taras"

# bool – True або False
n = True

# list – список
list1 = [1, 2, 3, 4]

# tuple – кортеж
tpl = (1, 2, 3, 4)

# dict – словник (ключ: значення)
dct = {
    10: "1",
    20: "20"
}

# set – множина
st = {1, 2, 3, 4}

# Арифметичні оператори
x = 10
y = 3

print(x + y)   # додавання
print(x - y)   # віднімання
print(x * y)   # множення
print(x / y)   # ділення
print(x // y)  # цілочисельне ділення
print(x % y)   # остача від ділення
print(x ** y)  # піднесення до степеня


# Оператори порівняння
print(x == y)  # дорівнює
print(x != y)  # не дорівнює
print(x > y)   # більше
print(x < y)   # менше
print(x >= y)  # більше або дорівнює
print(x <= y)  # менше або дорівнює


# Логічні оператори
a1 = True
b1 = False

print(a1 and b1)  # І
print(a1 or b1)   # АБО
print(not a1)     # НЕ

# Виведення типів
print(type(age))
print(type(a))
print(type(name))
print(type(n))
print(type(list1))
print(type(tpl))
print(type(dct))
print(type(st))